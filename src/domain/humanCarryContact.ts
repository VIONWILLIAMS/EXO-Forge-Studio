const clamp01 = (v: number) => Math.max(0, Math.min(1, v));
const mix = (a: number, b: number, u: number) => a + (b-a)*u;
const ease = (v: number) => { const u=clamp01(v); return u*u*u*(10+u*(-15+6*u)); };

export function sampleHumanCarryContactAngles(depth: number): ArmHandAngles {
  const x=clamp01(depth)*32, i=Math.min(31,Math.floor(x)), u=x-i;
  const at=(n: number,k: number) => CONTACT_LEFT[Math.max(0,Math.min(32,n))][k];
  const channel=(k: number) => {
    const a=at(i-1,k), b=at(i,k), c=at(i+1,k), d=at(i+2,k);
    return b+.5*u*(c-a+u*(2*a-5*b+4*c-d+u*(3*(b-c)+d-a)));
  };
  return [channel(0),channel(1),channel(2),channel(3),channel(4),channel(5),channel(6)];
}

// Call once on the fully constructed sampleCarry pose, using the local 0..14s clock.
// It only edits human arms/hands. Foot, root, box and mechanical-arm tracks stay intact.
export function applyHumanCarryContact(p: MotionPose, t: number): void {
  const weight=ease((t-.65)/.50)*(1-ease((t-12.75)/.55));
  if (weight<=0) return;
  const left=sampleHumanCarryContactAngles((p.pitch-.055)/.685);
  for (const side of ['L','R'] as const) {
    const q: ArmHandAngles=side==='L'?left:[left[0],-left[1],-left[2],left[3],-left[4],left[5],-left[6]];
    const arm=p[`arm${side}`], forearm=p[`forearm${side}`], hand=p[`hand${side}`];
    p[`arm${side}`]=[mix(arm[0],q[0],weight),mix(arm[1],q[1],weight),mix(arm[2],q[2],weight)];
    p[`forearm${side}`]=[mix(forearm[0],q[3],weight),forearm[1],forearm[2]];
    p[`hand${side}`]={...hand,
      curl:mix(hand.curl,0,weight),
      thumbCurl:mix(hand.thumbCurl??hand.curl,1,weight),
      roll:mix(hand.roll,q[4],weight),
      pitch:mix(hand.pitch,q[5],weight),
      yaw:mix(hand.yaw,q[6],weight),
    };
  }
}
